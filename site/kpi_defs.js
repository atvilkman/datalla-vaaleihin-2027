const COUNT_KEYS = ["E", "C", "Rt", "Rn", "Rp", "Rw", "L", "Mc", "Ac", "Acn", "T", "Tm", "Tc", "Tl", "sw", "AGn", "AGd", "GBn", "GBd",
  "CFy", "CFd", "S", "Smin", "Q", "MO", "fee", "feeMin", "feeMax"];

function pool(mps) {
  const c = Object.fromEntries(COUNT_KEYS.map(k => [k, 0]));
  const parts = { base: 0, speaker: 0, chair: 0, group_chair: 0, minister: 0 };
  let verified = true;
  for (const m of mps) {
    for (const k of COUNT_KEYS) c[k] += (k === "sw" ? (m.c.sw > 0 ? 1 : 0) : m.c[k] || 0);
    for (const k in parts) parts[k] += m.fee.parts[k] || 0;
    verified = verified && m.fee.verified;
  }
  if (mps.length === 1) c.sw = mps[0].c.sw;
  return { c, parts, verified, n: mps.length };
}
